#!/usr/bin/env python3
"""Launcher icon (design appIcon): sunflower #F2B705 background; a charcoal #1B1B1F 3x3 cube in isometric view, top
white, front red, right blue, with a pale gold #FFF4D6 turn arrow over the top layer. Writes the adaptive foreground
vector and colors; tools/make_icon.py --png OUT.png renders a 512 px PNG (pure Python rasteriser, no deps).
"""
import math, os, sys, struct, zlib
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "app", "src", "main", "res")
BG = (0xF2, 0xB7, 0x05)
INK = (0x1B, 0x1B, 0x1F)
W, H_, E = 27.0, 15.6, 31.0
Y0 = 54 - E / 2
P = {"L": (54 - W, Y0), "T": (54, Y0 - H_), "R": (54 + W, Y0), "C": (54, Y0 + H_), "BL": (54 - W, Y0 + E), "BR": (54 + W, Y0 + E), "B": (54, Y0 + H_ + E)}
def sub(a, b): return (a[0] - b[0], a[1] - b[1])
def add(a, b): return (a[0] + b[0], a[1] + b[1])
def mul(a, k): return (a[0] * k, a[1] * k)
FACES = [  # origin, u, v, colour
    (P["L"], sub(P["T"], P["L"]), sub(P["C"], P["L"]), (0xF4, 0xF4, 0xEF)),
    (P["L"], sub(P["C"], P["L"]), sub(P["BL"], P["L"]), (0xC8, 0x10, 0x2E)),
    (P["C"], sub(P["R"], P["C"]), sub(P["B"], P["C"]), (0x00, 0x46, 0xAD)),
]
HEX = [P["T"], P["R"], P["BR"], P["B"], P["BL"], P["L"]]
G = 0.09
def stickers():
    out = []
    for o, u, v, col in FACES:
        for i in range(3):
            for j in range(3):
                a, b = (i + G) / 3, (i + 1 - G) / 3
                c, d = (j + G) / 3, (j + 1 - G) / 3
                pts = [add(add(o, mul(u, a)), mul(v, c)), add(add(o, mul(u, b)), mul(v, c)), add(add(o, mul(u, b)), mul(v, d)), add(add(o, mul(u, a)), mul(v, d))]
                out.append((pts, col))
    return out
# arrow: an arc over the top face from the left corner region to the right, head at the right end
ARC_C, ARC_R = (54, Y0 - 4), 24.0
A0, A1 = math.radians(200), math.radians(330)
def arc_pts(n=24, r=ARC_R):
    return [(ARC_C[0] + r * math.cos(A0 + (A1 - A0) * k / n), ARC_C[1] + 0.55 * r * math.sin(A0 + (A1 - A0) * k / n)) for k in range(n + 1)]
def head():
    p = arc_pts()[-1]; q = arc_pts()[-3]
    d = sub(p, q); l = math.hypot(*d); d = (d[0] / l, d[1] / l); n = (-d[1], d[0])
    return [add(p, mul(d, 4.2)), add(sub(p, mul(n, 3.6)), mul(d, -1)), add(add(p, mul(n, 3.6)), mul(d, -1))]
def hexs(c): return "#FF%02X%02X%02X" % c
def path(pts): return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "Z"
def vector():
    s = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- generated by tools/make_icon.py (design appIcon): charcoal cube, white top / red front / blue right, gold turn arrow -->",
         '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
         f'    <path android:fillColor="{hexs(INK)}" android:pathData="{path(HEX)}" />']
    for pts, col in stickers():
        s.append(f'    <path android:fillColor="{hexs(col)}" android:pathData="{path(pts)}" />')
    a = arc_pts()
    s.append(f'    <path android:strokeColor="#FFFFF4D6" android:strokeWidth="3" android:strokeLineCap="round" android:fillColor="#00000000" android:pathData="M{a[0][0]:.2f},{a[0][1]:.2f} ' + " ".join(f"L{x:.2f},{y:.2f}" for x, y in a[1:]) + '" />')
    s.append(f'    <path android:fillColor="#FFFFF4D6" android:pathData="{path(head())}" />')
    s.append("</vector>")
    return "\n".join(s) + "\n"
def inside(pt, poly):
    x, y = pt; c = False
    for i in range(len(poly)):
        x1, y1 = poly[i]; x2, y2 = poly[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1: c = not c
    return c
def seg_dist(p, a, b):
    ab = sub(b, a); ap = sub(p, a); t = max(0, min(1, (ap[0] * ab[0] + ap[1] * ab[1]) / (ab[0] ** 2 + ab[1] ** 2)))
    q = add(a, mul(ab, t)); return math.hypot(p[0] - q[0], p[1] - q[1])
def png(out, size=512):
    shapes = [(HEX, INK)] + stickers()
    arc = arc_pts(); hd = head(); gold = (0xFF, 0xF4, 0xD6)
    rows = []
    ss = 3
    for py in range(size):
        row = bytearray([0])
        for px in range(size):
            acc = [0, 0, 0]
            for sy in range(ss):
                for sx in range(ss):
                    x = (px + (sx + 0.5) / ss) * 108 / size; y = (py + (sy + 0.5) / ss) * 108 / size
                    col = BG
                    for poly, c in shapes:
                        if inside((x, y), poly): col = c
                    if any(seg_dist((x, y), arc[k], arc[k + 1]) < 1.5 for k in range(len(arc) - 1)) or inside((x, y), hd): col = gold
                    acc = [acc[i] + col[i] for i in range(3)]
            row += bytes(int(v / (ss * ss)) for v in acc)
        rows.append(bytes(row))
    raw = zlib.compress(b"".join(rows), 9)
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    with open(out, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)) + chunk(b"IDAT", raw) + chunk(b"IEND", b""))
    print("wrote", out)
if __name__ == "__main__":
    open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w").write(vector())
    open(os.path.join(RES, "values", "colors.xml"), "w").write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- design appIcon 向日葵黄 #F2B705 -->\n    <color name="ic_launcher_background">#FFF2B705</color>\n</resources>\n')
    if "--png" in sys.argv: png(sys.argv[sys.argv.index("--png") + 1], int(sys.argv[sys.argv.index("--size") + 1]) if "--size" in sys.argv else 512)
